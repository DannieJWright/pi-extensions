export interface Paths {
	src: string;
	out: string;
	state: string;
	settings: string;
	subagentsState: string;
	subagentConfig?: string;
}
export interface RunOptions extends Paths { action: "gen" | "check"; force?: boolean }
export type RunStatus = "clean" | "wrote" | "drift" | "error";
export interface RunResult { status: RunStatus; lines: string[] }
const agentDir = path.join(homedir(), ".pi", "agent");
const configDir = path.join(agentDir, "permission-mode");
export const defaultPaths: Paths = {
	src: path.join(agentDir, "permissions.src.jsonc"),
	out: path.join(configDir, "permission-mode.json"),
	state: path.join(configDir, ".last-generated.json"),
	settings: path.join(agentDir, "settings.json"),
	subagentsState: path.join(agentDir, ".subagents.last-generated.json"),
	subagentConfig: path.join(agentDir, "extensions", "subagent", "config.json"),
};
const oldSrc = path.join(configDir, "permission-mode.src.jsonc");
const COMMENT_HEADER = "Generated from permissions.src.jsonc. Do not edit this file by hand.";
function isObject(value: unknown): value is JsonObject { return typeof value === "object" && value !== null && !Array.isArray(value); }
function message(error: unknown): string { return error instanceof Error ? error.message : String(error); }
function code(error: unknown): string | undefined { return (error as NodeJS.ErrnoException)?.code; }

export function resolveFiles(value: unknown, sourceFile: string, keyPath = ""): unknown {
	if (Array.isArray(value)) return value.map((item, index) => resolveFiles(item, sourceFile, `${keyPath}[${index}]`));
	if (!isObject(value)) return value;
	if (Object.keys(value).length === 1 && Object.hasOwn(value, "$file")) {
		if (typeof value.$file !== "string") throw new Error(`${keyPath}: $file must be a path string`);
		const file = path.resolve(path.dirname(sourceFile), value.$file);
		try { return fs.readFileSync(file, "utf8"); }
		catch (error) { throw new Error(`${keyPath}: cannot read $file ${file}: ${message(error)}`); }
	}
	return Object.fromEntries(Object.entries(value).map(([key, child]) => [key, resolveFiles(child, sourceFile, keyPath ? `${keyPath}.${key}` : key)]));
}

const MISSING = Symbol("missing");
function readJson(file: string): unknown | typeof MISSING {
	let text: string;
	try { text = fs.readFileSync(file, "utf8"); }
	catch (error) { if (code(error) === "ENOENT") return MISSING; throw error; }
	try { return JSON.parse(text); }
	catch (error) { throw new Error(`${file}: not valid JSON (${message(error)})`); }
}
function atomicWrite(file: string, text: string, assertOwned: () => void): void {
	const target = physicalPath(file);
	mkdirDurably(path.dirname(target));
	let mode = 0o600;
	try { mode = fs.statSync(target).mode & 0o777; } catch (error) { if (code(error) !== "ENOENT") throw error; }
	const temp = path.join(path.dirname(target), `.${path.basename(target)}.${randomUUID()}.tmp`);
	try {
		fs.writeFileSync(temp, text, { flag: "wx", mode });
		fs.chmodSync(temp, mode);
		const fd = fs.openSync(temp, "r");
		try { fs.fsyncSync(fd); } finally { fs.closeSync(fd); }
		assertOwned();
		fs.renameSync(temp, target);
		syncDirectory(path.dirname(target));
	} finally { try { fs.unlinkSync(temp); } catch (error) { if (code(error) !== "ENOENT") throw error; } }
}
function writeJson(file: string, value: unknown, assertOwned: () => void): void {
	atomicWrite(file, `${JSON.stringify(value, null, 2)}\n`, assertOwned);
}
function jsonEqual(a: unknown, b: unknown): boolean { return JSON.stringify(a) === JSON.stringify(b); }
function formatValue(value: unknown): string {
	const text = value === MISSING ? "(missing)" : JSON.stringify(value) ?? "undefined";
	return text.length > 120 ? `${text.slice(0, 120)}...` : text;
}
export function compareJson(left: unknown, right: unknown, leftLabel: string, rightLabel: string, prefix = ""): string[] {
	const here = prefix || "(root)";
	if (jsonEqual(left, right)) return [];
	if (isObject(left) && isObject(right)) {
		const lines: string[] = [];
		for (const key of Object.keys(left)) {
			if (!Object.hasOwn(right, key)) lines.push(`${here}.${key}  ${leftLabel}=${formatValue(left[key])}  ${rightLabel}=(missing)`);
			else lines.push(...compareJson(left[key], right[key], leftLabel, rightLabel, `${here}.${key}`));
		}
		for (const key of Object.keys(right)) if (!Object.hasOwn(left, key)) lines.push(`${here}.${key}  ${leftLabel}=(missing)  ${rightLabel}=${formatValue(right[key])}`);
		return lines;
	}
	if (Array.isArray(left) && Array.isArray(right)) {
		const lines: string[] = [];
		for (let i = 0; i < Math.max(left.length, right.length); i++) lines.push(...compareJson(left[i], right[i], leftLabel, rightLabel, `${here}[${i}]`));
		return lines;
	}
	return [`${here}  ${leftLabel}=${formatValue(left)}  ${rightLabel}=${formatValue(right)}`];
}
function validatePaths(paths: Paths): void {
	const entries = [...Object.entries(paths).filter((entry): entry is [string, string] => typeof entry[1] === "string"), ["modes pending", `${physicalPath(paths.out)}.generator-pending`], ["settings pending", `${physicalPath(paths.settings)}.generator-pending`]];
	if (paths.subagentConfig) entries.push(["config pending", `${physicalPath(paths.subagentConfig)}.generator-pending`]);
	const resolved = entries.map(([name, file]) => ({ name, file, physical: physicalPath(file) }));
	for (const item of resolved.filter((entry) => entry.name.endsWith(" pending"))) {
		try { if (fs.lstatSync(item.file).isSymbolicLink()) throw new Error(`${item.name}: refusing symlink at ${item.file}`); }
		catch (error) { if (code(error) !== "ENOENT") throw error; }
	}
	for (let i = 0; i < resolved.length; i++) for (let j = 0; j < i; j++) {
		const a = resolved[i], b = resolved[j];
		let same = a.physical === b.physical;
		try { const x = fs.statSync(a.file), y = fs.statSync(b.file); same ||= x.dev === y.dev && x.ino === y.ino; } catch (error) { if (code(error) !== "ENOENT") throw error; }
		if (same) throw new Error(`colliding paths: ${a.name} and ${b.name} (${a.file}, ${b.file})`);
	}
}

interface OutputSpec {
	name: string; out: string; state: string; desired: unknown;
	read(): { current: unknown; baseline: unknown };
	write(assertOwned: () => void): void;
	adopt(assertOwned: () => void): void;
	equal(a: unknown, b: unknown): boolean;
	needsAdoption?: boolean;
}
function processOutput(spec: OutputSpec, action: "gen" | "check", force: boolean, assertOwned: () => void): RunResult {
	const { current, baseline } = spec.read();
	const pending = `${physicalPath(spec.out)}.generator-pending`;
	const interrupted = fs.existsSync(pending);
	const matching = spec.equal(current, spec.desired);
	const modified = baseline === MISSING ? current !== MISSING && !matching : !spec.equal(current, baseline);
	if ((interrupted || modified) && !(action === "gen" && force)) {
		return { status: "drift", lines: [
			`${spec.name}: ${interrupted ? `unfinished output/baseline update (${pending}); inspect the output and use --force to recover` : "output has unadopted changes"}`,
			...compareJson(baseline === MISSING ? spec.desired : baseline, current, baseline === MISSING ? "generated" : "last generated", "file", spec.name),
		] };
	}
	if (action === "check") return matching && !interrupted
		? { status: "clean", lines: [] }
		: { status: "drift", lines: [`${spec.name}: output differs from source`, ...compareJson(spec.desired, current, "generated", "file", spec.name)] };
	if (!matching || interrupted || modified) {
		writeJson(pending, { output: spec.out, state: spec.state }, assertOwned);
		spec.write(assertOwned);
		spec.adopt(assertOwned);
		assertOwned();
		fs.unlinkSync(pending);
		syncDirectory(path.dirname(pending));
		return { status: "wrote", lines: [`${spec.name}: wrote ${spec.out}`] };
	}
	if (baseline === MISSING || spec.needsAdoption) spec.adopt(assertOwned);
	return { status: "clean", lines: [] };
}


function validatePermissions(config: JsonObject): void {
	if (!Object.hasOwn(config, "permissions")) return;
	const permissions = config.permissions;
	if (!isObject(permissions)) throw new Error("config.permissions must be an object.");
	const unknown = Object.keys(permissions).filter((key) => key !== "rules");
	if (unknown.length) throw new Error(`config.permissions has unsupported fields: ${unknown.join(", ")}.`);
	if (!Object.hasOwn(permissions, "rules")) return;
	const rules = permissions.rules;
	if (!isObject(rules)) throw new Error("config.permissions.rules must be an object mapping tool names to allow, ask, or deny.");
	const wait = isObject(config.waitTool) && typeof config.waitTool.name === "string" ? config.waitTool.name : "bg_wait";
	for (const [tool, decision] of Object.entries(rules)) {
		if (!tool.trim()) throw new Error("config.permissions.rules contains an empty tool name.");
		if (tool === "bash") throw new Error("config.permissions.rules.bash is unsupported; pi-subagents leaves bash policy to pi-guard.");
		if (["bg_wait", wait, "contact_supervisor", "intercom", "structured_output"].includes(tool)) throw new Error(`config.permissions.rules.${tool} is reserved for child coordination and cannot be gated.`);
		if (!["allow", "ask", "deny"].includes(decision as string)) throw new Error(`config.permissions.rules.${tool} must be allow, ask, or deny.`);
	}
}

function configOutput(source: JsonObject, filePath: string, state: string): OutputSpec {
	const desired = buildSubagentConfig(source);
	const file = readJson(filePath), base = readJson(state);
	if (file !== MISSING && !isObject(file)) throw new Error(`${filePath}: top level must be an object`);
	if (base !== MISSING && !isObject(base)) throw new Error(`${state}: top level must be an object`);
	if (isObject(base) && Object.hasOwn(base, "config") && !isObject(base.config)) throw new Error(`${state}: config baseline must be an object`);
	const previous = isObject(base) && isObject(base.config) ? base.config : {};
	const existing = isObject(file) ? file : {};
	const candidate: JsonObject = { ...existing };
	for (const key of Object.keys(previous)) if (!Object.hasOwn(desired, key)) delete candidate[key];
	for (const [key, value] of Object.entries(desired)) candidate[key] = value;
	validatePermissions(candidate);
	const current: JsonObject = {}, baseline: JsonObject = { ...previous };
	for (const key of new Set([...Object.keys(previous), ...Object.keys(desired)])) {
		if (Object.hasOwn(existing, key)) current[key] = existing[key];
		if (!Object.hasOwn(previous, key) && Object.hasOwn(existing, key) && !settingsEqual(existing[key], desired[key], "config")) baseline[key] = desired[key];
		else if (!Object.hasOwn(previous, key) && Object.hasOwn(existing, key)) baseline[key] = existing[key];
	}
	return {
		name: "subagents.config", out: filePath, state, desired, equal: (a, b) => settingsEqual(a, b, "config"),
		needsAdoption: !isObject(base) || !Object.hasOwn(base, "config") || !settingsEqual(previous, desired, "config"),
		read: () => ({ current, baseline }),
		write: (owned) => writeJson(filePath, candidate, owned),
		adopt: (owned) => {
			const latest = readJson(state);
			if (latest !== MISSING && !isObject(latest)) throw new Error(`${state}: top level must be an object`);
			writeJson(state, { ...(isObject(latest) ? latest : {}), config: desired }, owned);
		},
	};
}

export async function run(options: RunOptions): Promise<RunResult> {
	try {
		const { src, out, state, settings, subagentsState, action } = options;
		const subagentConfig = options.subagentConfig ?? defaultPaths.subagentConfig!;
		validatePaths({ src, out, state, settings, subagentsState });
		const loadSpecs = (): { specs: OutputSpec[]; configSource?: JsonObject } => {
			if (!fs.existsSync(src)) {
				if (fs.existsSync(oldSrc)) throw new Error(`${src} not found; old source exists at ${oldSrc}. Run just perm migrate; see MIGRATION.md.`);
				throw new Error(`${src} not found. Copy configs/permissions.example.src.jsonc there first.`);
			}
			const parsed = parseJsonc(fs.readFileSync(src, "utf8"), src);
			if (!isObject(parsed)) throw new Error(`${src}: top level must be an object`);
			for (const key of Object.keys(parsed)) if (key !== "permissionModes" && key !== "subagents") throw new Error(`${src}: unknown top-level key ${key}; migrate the old source with just perm migrate (see MIGRATION.md)`);
			if (!isObject(parsed.permissionModes)) throw new Error("permissionModes: must be an object");
			if (Object.hasOwn(parsed, "subagents") && !isObject(parsed.subagents)) throw new Error("subagents: must be an object");
			const source = resolveFiles(parsed, src) as JsonObject;
			const rendered = { $comment: COMMENT_HEADER, ...buildConfig(source.permissionModes as JsonObject) };
			const subagents = isObject(source.subagents) ? buildSubagents(source.subagents) : undefined;
			const specs: OutputSpec[] = [{
				name: "permissionModes", out, state, desired: rendered, equal: jsonEqual,
				read: () => ({ current: readJson(out), baseline: readJson(state) }),
				write: (owned) => writeJson(out, rendered, owned),
				adopt: (owned) => writeJson(state, rendered, owned),
			}];
			if (subagents !== undefined) specs.push({
				name: "subagents", out: settings, state: subagentsState, desired: subagents, equal: settingsEqual,
				read: () => {
					const file = readJson(settings), base = readJson(subagentsState);
					if (file !== MISSING && !isObject(file)) throw new Error(`${settings}: top level must be an object`);
					if (base !== MISSING && !isObject(base)) throw new Error(`${subagentsState}: top level must be an object`);
					return { current: isObject(file) && Object.hasOwn(file, "subagents") ? file.subagents : MISSING, baseline: isObject(base) && Object.hasOwn(base, "settings") ? base.settings : MISSING };
				},
				write: (owned) => {
					const file = readJson(settings);
					if (file !== MISSING && !isObject(file)) throw new Error(`${settings}: top level must be an object`);
					writeJson(settings, { ...(isObject(file) ? file : {}), subagents }, owned);
				},
				adopt: (owned) => {
					const file = readJson(subagentsState);
					if (file !== MISSING && !isObject(file)) throw new Error(`${subagentsState}: top level must be an object`);
					writeJson(subagentsState, { ...(isObject(file) ? file : {}), settings: subagents }, owned);
				},
			});
			const configSource = isObject(source.subagents) && Object.hasOwn(source.subagents, "config") ? source.subagents : undefined;
			if (configSource) validatePaths({ src, out, state, settings, subagentsState, subagentConfig });
			return { specs, configSource };
		};
		const process = ({ specs, configSource }: { specs: OutputSpec[]; configSource?: JsonObject }, owned: () => void): RunResult => {
			const jobs = specs.map((spec) => () => processOutput(spec, action, !!options.force, owned));
			if (configSource) jobs.push(() => processOutput(configOutput(configSource, subagentConfig, subagentsState), action, !!options.force, owned));
			const results = jobs.map((job) => { try { return job(); } catch (error) { return { status: "error" as const, lines: [message(error)] }; } });
			const status: RunStatus = results.some((x) => x.status === "error") ? "error" : results.some((x) => x.status === "drift") ? "drift" : results.some((x) => x.status === "wrote") ? "wrote" : "clean";
			const lines = results.flatMap((x) => x.lines);
			if (results.some((x, i) => i === 1 && x.status === "drift")) lines.push("pi-subagents disable, enable, eject and reset modify subagents; move those changes into the source or use --force.");
			return { status, lines };
		};
		if (action === "check") return process(loadSpecs(), () => {});
		for (;;) {
			const initial = loadSpecs();
			const result = await withOutputLocks([...initial.specs.flatMap((spec) => [spec.out, spec.state]), ...(initial.configSource ? [subagentConfig, subagentsState] : [])], initial.specs.length === 1 ? undefined : settings, (owned) => {
				validatePaths({ src, out, state, settings, subagentsState });
				const current = loadSpecs();
				// An added or removed section changes the lock set; retry with the right one.
				return current.specs.length === initial.specs.length && !!current.configSource === !!initial.configSource ? process(current, owned) : undefined;
			});
			if (result !== undefined) return result;
		}
	} catch (error) { return { status: "error", lines: [message(error)] }; }
}
export function formatResult(result: RunResult, _paths: Paths): string | null {
	if (result.status === "clean") return null;
	return [`permissions generator: ${result.status}`, ...result.lines, result.status === "drift" ? "Move changes into permissions.src.jsonc or run `just perm gen --force`." : ""].filter(Boolean).join("\n");
}
function parseArgs(argv: string[]): { action: "gen" | "check" | "migrate"; paths: Paths; force: boolean } {
	const action = argv[0] ?? "gen";
	if (action !== "gen" && action !== "check" && action !== "migrate") throw new Error(`unknown action: ${action}`);
	const paths = { ...defaultPaths };
	let force = false;
	const flags: Record<string, keyof Paths> = { "--src": "src", "--modes-out": "out", "--modes-state": "state", "--settings": "settings", "--subagents-state": "subagentsState", "--subagent-config": "subagentConfig" };
	for (let i = 1; i < argv.length; i++) {
		const arg = argv[i];
		if (arg === "--force") { force = true; continue; }
		const key = flags[arg];
		if (!key) throw new Error(`unknown argument: ${arg}`);
		const value = argv[++i];
		if (!value || value.startsWith("--")) throw new Error(`${arg} needs a path`);
		paths[key] = path.resolve(value);
	}
	return { action, paths, force };
}
async function main(): Promise<void> {
	try {
		const { action, paths, force } = parseArgs(process.argv.slice(2));
		if (action === "migrate") {
			validatePaths(paths);
			migrate({ oldSrc, src: paths.src, settings: paths.settings });
			process.stderr.write("Migration created the new source; run just perm check, then review and regenerate as needed. The old source was retained. See MIGRATION.md.\n");
			return;
		}
		const result = await run({ ...paths, action, force });
		const report = formatResult(result, paths);
		if (report) process.stderr.write(`${report}\n`);
		if (result.status === "drift") process.exitCode = 1;
		if (result.status === "error") process.exitCode = 2;
	} catch (error) { process.stderr.write(`${message(error)}\n`); process.exitCode = 2; }
}
if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url))) await main();
