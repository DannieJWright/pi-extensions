// Generator entry: build the permission-mode config from permission-mode.src.jsonc.
// Used by the CLI (`node generate.ts gen|check`) and by index.ts (the pi extension).

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { parseJsonc } from "./jsonc.ts";
import { buildConfig, type JsonObject } from "./merge.ts";

export interface Paths {
	src: string;
	out: string;
	state: string;
}

export interface RunOptions extends Paths {
	action: "gen" | "check";
	force?: boolean;
}

export type RunStatus = "clean" | "wrote" | "drift" | "error";

export interface RunResult {
	status: RunStatus;
	lines: string[];
}

const scriptDir = path.dirname(fileURLToPath(import.meta.url));

export const defaultPaths: Paths = {
	src: path.join(scriptDir, "permission-mode.src.jsonc"),
	out: path.resolve(scriptDir, "..", "..", "permission-mode", "permission-mode.json"),
	state: path.join(scriptDir, ".last-generated.json"),
};

const COMMENT_HEADER = "Generated from permission-mode.src.jsonc. Do not edit this file by hand.";

function isObject(value: unknown): value is JsonObject {
	return typeof value === "object" && value !== null && !Array.isArray(value);
}

function message(error: unknown): string {
	return error instanceof Error ? error.message : String(error);
}

function readJsonFile(file: string): unknown | null {
	if (!fs.existsSync(file)) return null;
	const text = fs.readFileSync(file, "utf8");
	try {
		return JSON.parse(text);
	} catch (error) {
		throw new Error(`${file}: not valid JSON (${message(error)})`);
	}
}

function writeJsonFile(file: string, value: unknown): void {
	fs.mkdirSync(path.dirname(file), { recursive: true });
	fs.writeFileSync(file, `${JSON.stringify(value, null, 2)}\n`);
}

function jsonEqual(a: unknown, b: unknown): boolean {
	return JSON.stringify(a) === JSON.stringify(b);
}

function formatValue(value: unknown): string {
	const text = JSON.stringify(value) ?? "undefined";
	return text.length > 120 ? `${text.slice(0, 120)}...` : text;
}

/** Compare two JSON values. Returns one line per differing key path. */
export function compareJson(left: unknown, right: unknown, leftLabel: string, rightLabel: string, prefix = ""): string[] {
	const here = prefix || "(root)";
	if (jsonEqual(left, right)) return [];

	if (isObject(left) && isObject(right)) {
		const lines: string[] = [];
		for (const key of Object.keys(left)) {
			if (!(key in right)) {
				lines.push(`${here}.${key}  ${leftLabel}=${formatValue(left[key])}  ${rightLabel}=(missing)`);
				continue;
			}
			lines.push(...compareJson(left[key], right[key], leftLabel, rightLabel, `${here}.${key}`));
		}
		for (const key of Object.keys(right)) {
			if (!(key in left)) {
				lines.push(`${here}.${key}  ${leftLabel}=(missing)  ${rightLabel}=${formatValue(right[key])}`);
			}
		}
		return lines;
	}

	if (Array.isArray(left) && Array.isArray(right)) {
		const lines: string[] = [];
		const length = Math.max(left.length, right.length);
		for (let i = 0; i < length; i += 1) {
			if (i >= left.length || i >= right.length) {
				lines.push(`${here}[${i}]  ${leftLabel}=${formatValue(left[i])}  ${rightLabel}=${formatValue(right[i])}`);
				continue;
			}
			lines.push(...compareJson(left[i], right[i], leftLabel, rightLabel, `${here}[${i}]`));
		}
		return lines;
	}

	return [`${here}  ${leftLabel}=${formatValue(left)}  ${rightLabel}=${formatValue(right)}`];
}

export function run(options: RunOptions): RunResult {
	const { src, out, state, action } = options;

	let generated: JsonObject;
	try {
		const sourceText = fs.readFileSync(src, "utf8");
		const parsed = parseJsonc(sourceText, src);
		if (!isObject(parsed)) throw new Error(`${src}: top level must be an object`);
		generated = buildConfig(parsed);
	} catch (error) {
		return { status: "error", lines: [message(error)] };
	}

	const rendered: JsonObject = { $comment: COMMENT_HEADER, ...generated };

	let file: unknown | null;
	let baseline: unknown | null;
	try {
		file = readJsonFile(out);
		baseline = readJsonFile(state);
	} catch (error) {
		return { status: "error", lines: [message(error)] };
	}

	// The output differs from what the generator last wrote: something else changed it.
	if (file !== null && baseline !== null && !jsonEqual(file, baseline)) {
		const lines = compareJson(baseline, file, "last generated", "file");
		if (action === "gen" && options.force) {
			writeJsonFile(out, rendered);
			writeJsonFile(state, rendered);
			return { status: "wrote", lines: ["overwrote drift:", ...lines] };
		}
		return { status: "drift", lines };
	}

	if (file === null || !jsonEqual(file, rendered)) {
		const lines = file === null ? [`created ${out}`] : compareJson(rendered, file, "generated", "file");
		if (action === "check") {
			return { status: "drift", lines: file === null ? lines : ["output is not what the source generates:", ...lines] };
		}
		writeJsonFile(out, rendered);
		writeJsonFile(state, rendered);
		return { status: "wrote", lines };
	}

	// Clean: the file matches the source. Keep the baseline record in place.
	if (baseline === null) writeJsonFile(state, rendered);
	return { status: "clean", lines: [] };
}

/** One-line report for a run. Returns null when there is nothing to report. */
export function formatResult(result: RunResult, paths: Paths): string | null {
	if (result.status === "clean") return null;
	if (result.status === "error") return `permission-mode generator: ${result.lines.join("\n")}`;

	const header = result.status === "wrote"
		? `permission-mode generator: wrote ${paths.out}`
		: `permission-mode generator: ${paths.out} does not match ${paths.state}`;

	const hint = result.status === "drift" ? "Move the change into permission-mode.src.jsonc, or run `just perm gen --force`." : "";
	return [header, ...result.lines, hint].filter(Boolean).join("\n");
}

function parseArgs(argv: string[]): RunOptions {
	const action = argv[0] === "check" ? "check" : "gen";
	const options: RunOptions = { ...defaultPaths, action, force: false };

	for (let i = 1; i < argv.length; i += 1) {
		const arg = argv[i];
		if (arg === "--force") {
			options.force = true;
			continue;
		}
		if (arg === "--src" || arg === "--out" || arg === "--state") {
			const value = argv[i + 1];
			if (!value) throw new Error(`${arg} needs a path`);
			options[arg.slice(2) as keyof Paths] = path.resolve(value);
			i += 1;
			continue;
		}
		throw new Error(`unknown argument: ${arg}`);
	}

	return options;
}

function main(): void {
	let options: RunOptions;
	try {
		options = parseArgs(process.argv.slice(2));
	} catch (error) {
		process.stderr.write(`${message(error)}\n`);
		process.exitCode = 2;
		return;
	}

	const result = run(options);
	const report = formatResult(result, options);
	if (report) process.stderr.write(`${report}\n`);

	if (result.status === "drift") process.exitCode = 1;
	if (result.status === "error") process.exitCode = 2;
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url))) {
	main();
}
